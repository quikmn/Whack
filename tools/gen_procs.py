"""Build ProcData.lua: the weapon enchants whose procs Whack shows as a "boom".

Reads the client tables ForeverMiner exports (SpellItemEnchantment, SpellName, SpellMisc, SpellEffect) and keeps the
permanent weapon enchants (Duration 0) with a proc spell (Effect type 1, EffectArg = spell ID). Each proc is one of:
  hit    - the spell deals damage to the target (Fiery Weapon, Lifestealing, Demonslaying)
  debuff - the spell only puts an aura on the target (Icy Chill, Unholy Weapon): seen as its debuff, or a resist
  buff   - the spell puts an aura on you (Crusader's Holy Strength)

Usage: python tools/gen_procs.py [tables dir]   (default D:/Dev/ForeverMiner/out/tables)
"""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLES = sys.argv[1] if len(sys.argv) > 1 else "D:/Dev/ForeverMiner/out/tables"

DAMAGE = {"2", "9"}        # SCHOOL_DAMAGE, HEALTH_LEECH
APPLY_AURA = "6"
SELF = "1"                 # ImplicitTarget: caster
TEMP_ICON = 136235         # interface/icons/temp.blp: the spell has no real icon
# a fitting icon per school when the proc spell has none (file IDs from the client's listfile)
SCHOOL_ICON = {1: 132147, 2: 135920, 4: 135808, 8: 136048, 16: 135846, 32: 136169, 64: 135735}


def rows(name):
    with open(os.path.join(TABLES, name + ".csv"), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    names = {r["ID"]: r["Name_lang"] for r in rows("SpellName")}
    misc = {}
    for r in rows("SpellMisc"):
        misc.setdefault(r["SpellID"], r)
    effects = {}
    for r in rows("SpellEffect"):
        effects.setdefault(r["SpellID"], []).append(r)

    out = []
    for e in rows("SpellItemEnchantment"):
        if e["Duration"] != "0":
            continue  # oils, poisons, totems, shaman weapon spells: temporary
        for i in range(3):
            if e[f"Effect[{i}]"] != "1":
                continue
            spell = e[f"EffectArg[{i}]"]
            m = misc.get(spell)
            effs = effects.get(spell, [])
            if not m or not effs:
                continue
            kinds = set()
            for x in effs:
                if x["Effect"] in DAMAGE and x["ImplicitTarget[0]"] != SELF:
                    kinds.add("hit")
                elif x["Effect"] == APPLY_AURA:
                    kinds.add("buff" if x["ImplicitTarget[0]"] == SELF else "debuff")
            kind = "hit" if "hit" in kinds else "buff" if "buff" in kinds else "debuff" if "debuff" in kinds else None
            if not kind:
                continue
            name = e["Name_lang"]
            if name.lower().startswith("enchant: "):
                name = name[9:]
            school = int(m["SchoolMask"])
            icon = int(m["SpellIconFileDataID"] or 0)
            if icon in (0, TEMP_ICON):
                icon = SCHOOL_ICON.get(school, 0)
            out.append((int(e["ID"]), name, int(spell), names.get(spell, name), school, kind, icon))

    lines = [
        "-- Generated by tools/gen_procs.py from the client's SpellItemEnchantment table. Do not edit by hand.",
        "-- [enchant ID] = { name, proc spell ID, proc spell name, school mask, kind (hit | debuff | buff), icon }",
        "local _, ns = ...",
        "ns.PROC_ENCHANTS = {",
    ]
    for eid, name, spell, sname, school, kind, icon in sorted(out):
        lines.append(f"\t[{eid}] = {{ name = {lua_str(name)}, spell = {spell}, spellName = {lua_str(sname)}, "
                     f"school = {school}, kind = \"{kind}\", icon = {icon} }},")
    lines.append("}")
    with open(os.path.join(ROOT, "ProcData.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(out)} proc enchants -> ProcData.lua")


if __name__ == "__main__":
    main()
